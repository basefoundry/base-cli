#!/usr/bin/env python3
"""Generate the small ``base_cli.core`` facade from the API manifest."""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

from api_manifest import load_manifest

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "docs" / "api-manifest.json"
CORE = ROOT / "lib" / "python" / "base_cli" / "core.py"
MARKER = "# generated by scripts/generate_core_surface.py; do not edit"

# These are the package modules that own the stable core names. The manifest
# remains the source of truth for which names belong to the core tier; this
# mapping only records how Python resolves those names for the generated file.
CORE_SOURCE_MODULES = {
    "App": ".app",
    "argument": ".app",
    "attach": ".app",
    "command": ".app",
    "option": ".app",
    "run_app": ".app",
    "ApplicationStateT": ".context",
    "ConfigT": ".context",
    "Context": ".context",
    "ServicesT": ".context",
    "get_current_context": ".context",
    "BaseCliDeprecationWarning": ".deprecations",
    "deprecated": ".deprecations",
    "ConfigurationError": ".errors",
    "ExitCode": ".exit_codes",
    "LIFECYCLE_META_KEY": ".lifecycle_options",
    "LifecycleOption": ".lifecycle_options",
    "LifecycleOptions": ".lifecycle_options",
    "LifecycleValues": ".lifecycle_options",
    "get_lifecycle_values": ".lifecycle_options",
    "configure_logger": ".logging",
    "log_critical": ".logging",
    "log_debug": ".logging",
    "log_error": ".logging",
    "log_info": ".logging",
    "log_warning": ".logging",
    "__version__": ".",
    "testing": ".",
}


def _core_names(manifest: dict[str, Any]) -> list[str]:
    tiers = manifest.get("tiers")
    if not isinstance(tiers, dict) or not isinstance(tiers.get("core"), list):
        raise ValueError("API manifest tiers.core must be a list")
    names = tiers["core"]
    if any(not isinstance(name, str) for name in names):
        raise ValueError("API manifest tiers.core must contain only strings")
    missing = sorted(set(names) - set(CORE_SOURCE_MODULES))
    if missing:
        raise ValueError(f"no core import mapping exists for: {missing}")
    return names


def render(manifest: dict[str, Any]) -> str:
    names = _core_names(manifest)
    grouped: dict[str, list[str]] = {}
    for name in names:
        grouped.setdefault(CORE_SOURCE_MODULES[name], []).append(name)

    lines = [
        '"""Small, stable starting surface for production CLI applications.',
        "",
        "The compatibility facade at :mod:`base_cli` remains broad during the 0.x",
        "series. New applications should prefer this module for the lifecycle core;",
        "integration and advanced APIs stay behind their explicit modules.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
    ]
    for module in (
        ".",
        ".app",
        ".context",
        ".deprecations",
        ".errors",
        ".exit_codes",
        ".lifecycle_options",
        ".logging",
    ):
        module_names = grouped.get(module)
        if not module_names:
            continue
        prefix = "from . import" if module == "." else f"from {module} import"
        if module == ".":
            lines.append(f"{prefix} {', '.join(module_names)}")
        else:
            lines.append(f"{prefix} (")
            lines.extend(f"    {name}," for name in module_names)
            lines.append(")")
    lines.extend(["", "__all__ = ["])
    lines.extend(f'    "{name}",' for name in names)
    lines.extend(["]", "", MARKER, ""])
    return "\n".join(lines)


def main() -> None:
    check = "--check" in sys.argv[1:]
    try:
        rendered = render(load_manifest(MANIFEST))
    except ValueError as exc:
        print(f"core surface generation failed: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc
    if check:
        current = CORE.read_text(encoding="utf-8") if CORE.exists() else ""
        if current != rendered:
            print(f"{CORE.relative_to(ROOT)} is stale; run scripts/generate_core_surface.py", file=sys.stderr)
            raise SystemExit(1)
        print(f"Validated {CORE.relative_to(ROOT)}.")
        return
    CORE.write_text(rendered, encoding="utf-8")
    print(f"Generated {CORE.relative_to(ROOT)}.")


if __name__ == "__main__":
    main()
